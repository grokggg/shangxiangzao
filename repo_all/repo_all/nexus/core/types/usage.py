"""Extended usage types for multi-provider compatibility."""

from __future__ import annotations

from openai.types import CompletionUsage
from openai.types.completion_usage import CompletionTokensDetails, PromptTokensDetails
from pydantic import BaseModel


class ExtendedPromptTokensDetails(PromptTokensDetails):
    """Extended prompt tokens details with provider-specific fields."""

    text_tokens: int | None = None
    """Text tokens sent to the model."""

    image_tokens: int | None = None
    """Image tokens sent to the model."""

    video_tokens: int | None = None
    """Video tokens sent to the model."""

    cache_creation_tokens: int | None = None
    """Number of cache creation tokens. Used for Anthropic prompt caching."""

    web_search_requests: int | None = None
    """Number of web search requests. Used for Anthropic."""


class ExtendedCompletionTokensDetails(CompletionTokensDetails):
    """Extended completion tokens details with provider-specific fields."""

    text_tokens: int | None = None
    """Text tokens generated by the model."""

    image_tokens: int | None = None
    """Image tokens generated by the model."""

    video_tokens: int | None = None
    """Video tokens generated by the model."""


class ExtendedUsage(BaseModel):
    """Extended usage statistics with provider-specific fields.

    Compatible with OpenAI's CompletionUsage but includes additional fields
    for multi-provider support (cost tracking, cache tokens, etc.).
    """

    prompt_tokens: int = 0
    """Number of tokens in the prompt."""

    completion_tokens: int = 0
    """Number of tokens in the generated completion."""

    total_tokens: int = 0
    """Total number of tokens used in the request (prompt + completion)."""

    completion_tokens_details: ExtendedCompletionTokensDetails | None = None
    """Breakdown of tokens used in a completion."""

    prompt_tokens_details: ExtendedPromptTokensDetails | None = None
    """Breakdown of tokens used in the prompt."""

    # Extended fields
    cache_creation_input_tokens: int = 0
    """Tokens used to create the cache entry. Used for Anthropic prompt caching."""

    cache_read_input_tokens: int = 0
    """Tokens read from cache. Used for Anthropic prompt caching."""

    cost: float | None = None
    """Calculated cost of the request. Provided by litellm."""

    @classmethod
    def from_openai(cls, usage: CompletionUsage | None) -> ExtendedUsage | None:
        """Create ExtendedUsage from OpenAI CompletionUsage."""
        if usage is None:
            return None

        prompt_details = None
        if usage.prompt_tokens_details:
            prompt_details = ExtendedPromptTokensDetails.model_validate(usage.prompt_tokens_details.model_dump())

        completion_details = None
        if usage.completion_tokens_details:
            completion_details = ExtendedCompletionTokensDetails.model_validate(
                usage.completion_tokens_details.model_dump()
            )

        return cls(
            prompt_tokens=usage.prompt_tokens,
            completion_tokens=usage.completion_tokens,
            total_tokens=usage.total_tokens,
            prompt_tokens_details=prompt_details,
            completion_tokens_details=completion_details,
            cache_creation_input_tokens=int(getattr(usage, 'cache_creation_input_tokens', 0) or 0),
            cache_read_input_tokens=int(getattr(usage, 'cache_read_input_tokens', 0) or 0),
            cost=getattr(usage, 'cost', None),
        )
