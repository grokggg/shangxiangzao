"""Extended completion types for multi-provider compatibility."""

from __future__ import annotations

from typing import Any

from openai.types.chat import ChatCompletion
from openai.types.chat.chat_completion import ChoiceLogprobs
from pydantic import BaseModel

from nexus.core.types.message import ExtendedMessage
from nexus.core.types.usage import ExtendedUsage


class ExtendedChoice(BaseModel):
    """Extended choice with provider-specific fields."""

    finish_reason: str
    """The reason the model stopped generating tokens."""

    index: int
    """The index of the choice in the list of choices."""

    message: ExtendedMessage
    """A chat completion message generated by the model."""

    logprobs: ChoiceLogprobs | None = None
    """Log probability information for the choice."""

    provider_specific_fields: dict[str, Any] | None = None
    """Additional provider-specific fields."""


class ExtendedChatCompletion(BaseModel):
    """Extended chat completion with provider-specific fields.

    Compatible with OpenAI's ChatCompletion but includes additional fields
    for multi-provider support.
    """

    id: str
    """A unique identifier for the chat completion."""

    choices: list[ExtendedChoice]
    """A list of chat completion choices."""

    created: int
    """The Unix timestamp (in seconds) of when the chat completion was created."""

    model: str | None = None
    """The model used for the chat completion."""

    object: str = 'chat.completion'
    """The object type."""

    system_fingerprint: str | None = None
    """Fingerprint representing the backend configuration."""

    usage: ExtendedUsage | None = None
    """Usage statistics for the completion request."""

    service_tier: str | None = None
    """Specifies the processing type used for serving the request."""

    provider_specific_fields: dict[str, Any] | None = None
    """Additional provider-specific fields."""

    @classmethod
    def from_openai(cls, completion: ChatCompletion) -> ExtendedChatCompletion:
        """Create ExtendedChatCompletion from OpenAI ChatCompletion."""
        choices = [
            ExtendedChoice(
                finish_reason=choice.finish_reason,
                index=choice.index,
                message=ExtendedMessage.from_openai(choice.message),
                logprobs=choice.logprobs,
                provider_specific_fields=getattr(choice, 'provider_specific_fields', None),
            )
            for choice in completion.choices
        ]

        return cls(
            id=completion.id,
            choices=choices,
            created=completion.created,
            model=completion.model,
            object=completion.object,
            system_fingerprint=completion.system_fingerprint,
            usage=ExtendedUsage.from_openai(completion.usage),
            service_tier=getattr(completion, 'service_tier', None),
            provider_specific_fields=getattr(completion, 'provider_specific_fields', None),
        )
